#include "../_启动窗口.h"

void __启动窗口::载入(窗口* 父窗, bool 模态)
{
	if (窗口句柄)return;
	窗口::参数 cs;
	cs.宽度 = 600;
	cs.高度 = 400;
	cs.标题 = L"网格布局演示";
	cs.边框 = 窗口边框::普通可调边框;
	cs.最大化按钮 = true;
	cs.最小化按钮 = true;
	窗口::创建(cs, 父窗, 模态);

	// ===== 创建控件 =====

	{
		按钮::参数 a{ 0, 0, 80, 30 };
		a.标题 = L"文件";
		按钮1.创建(a, this);
	}

	{
		按钮::参数 a{ 0, 0, 80, 30 };
		a.标题 = L"编辑";
		按钮2.创建(a, this);
	}

	{
		编辑框::参数 a{ 0, 0, 150, 100 };
		a.内容 = L"导航面板\r\n├ 首页\r\n├ 设置\r\n└ 关于";
		a.是否允许多行 = true;
		a.滚动条 = 编辑框滚动条::纵向滚动条;
		编辑框_导航.创建(a, this);
	}

	{
		编辑框::参数 a{ 0, 0, 300, 200 };
		a.内容 =
			L"欢迎使用白易 BEWin32UI 网格布局系统！\r\n\r\n"
			L"本窗口演示了 3 行 × 2 列的经典布局：\r\n"
			L"  · 顶部工具栏 — 固定 35vpx 高度\r\n"
			L"  · 左侧导航栏 — 固定 150vpx 宽度\r\n"
			L"  · 右侧内容区 — 比例 1* 自适应填满\r\n"
			L"  · 底部状态栏 — 固定 25vpx 高度，跨 2 列\r\n\r\n"
			L"请尝试拖拽窗口边框改变大小，观察各控件的自适应效果。";
		a.是否允许多行 = true;
		a.滚动条 = 编辑框滚动条::纵向滚动条;
		编辑框_内容.创建(a, this);
	}

	{
		标签::参数 a{ 0, 0, 200, 20 };
		a.标题 = L"状态栏 — 就绪";
		a.背景颜色 = 颜色(0xF0F0F0);
		a.纵向对齐方式 = 纵向对齐::居中;
		标签_状态栏.创建(a, this);
	}

	窗口::完毕(模态);
}