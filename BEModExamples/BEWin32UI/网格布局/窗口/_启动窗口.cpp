#include <BEMod.h>

struct __启动窗口 : 窗口
{
	网格布局 布局;

	void 事件_创建完毕()
	{
		// 1. 绑定宿主
		布局.绑定(this);

		// 2. 全局间距：四周内边距 10vpx，行列缝隙 6vpx
		布局.置内边距(10).置间距(6);

		// 3. 定义 3 行 x 2 列
		//    行0: 工具栏 固定35vpx  |  行1: 内容区 自适应(1*)  |  行2: 状态栏 固定25vpx
		//    列0: 导航栏 固定150vpx |  列1: 主内容 自适应(1*)
		布局.设置行({ 网格::像素(35), 网格::比例(1), 网格::像素(25) });
		布局.设置列({ 网格::像素(150), 网格::比例(1) });

		// 4. 放置控件到网格
		布局.放置(按钮1, 0, 0);                          // 工具栏左
		布局.放置(按钮2, 0, 1);                          // 工具栏右
		布局.放置(编辑框_导航, 1, 0);                    // 左侧导航
		布局.放置(编辑框_内容, 1, 1);                    // 右侧内容
		布局.放置(标签_状态栏, 2, 0, 1, 2, nil, nil, { 0, 5 });
		// 底部状态栏，跨1行跨2列，微调上边距

		// 5. 首次触发布局计算
		布局.刷新布局();
	}

	void 事件_尺寸被改变()
	{
		// 窗口拉伸时自动刷新布局
		布局.刷新布局();
	}

	void _按钮1_被单击()
	{
		信息框("你点击了 [文件] 按钮");
	}

	void _按钮2_被单击()
	{
		信息框("你点击了 [编辑] 按钮");
	}

#pragma region 组件成员
	struct _按钮1 : 按钮 {
		void 事件_被单击() { _启动窗口._按钮1_被单击(); }
	} 按钮1;

	struct _按钮2 : 按钮 {
		void 事件_被单击() { _启动窗口._按钮2_被单击(); }
	} 按钮2;

	编辑框 编辑框_导航;
	编辑框 编辑框_内容;
	标签 标签_状态栏;
#pragma endregion
	void 载入(窗口* 父窗 = 0, bool 模态 = 0);
	void 完毕(bool 模态 = 0);
} _启动窗口;