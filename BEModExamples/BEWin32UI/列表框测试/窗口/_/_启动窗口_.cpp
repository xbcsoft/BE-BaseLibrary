#include "../_启动窗口.h"

void __启动窗口::载入(窗口* 父窗, bool 模态)
{
	if (窗口句柄) return;
	窗口::参数 cs;
	cs.宽度 = 520;
	cs.高度 = 360;
	cs.标题 = L"列表框组件演示";
	cs.边框 = 窗口边框::普通固定边框;
	窗口::创建(cs, 父窗, 模态);

	// 1. 创建列表框 (左边20, 顶边20, 宽度200, 高度285)
	列表框::参数 lcs{ 20, 20, 200, 285 };
	lcs.边框 = 列表框边框::凹入式;
	lcs.行间距 = 2;
	列表框1.创建(lcs, this);

	// 填入初始测试项目
	列表框1.加入项目(L"苹果 (Apple)", 101);
	列表框1.加入项目(L"香蕉 (Banana)", 102);
	列表框1.加入项目(L"橙子 (Orange)", 103);
	列表框1.加入项目(L"西瓜 (Watermelon)", 104);
	列表框1.加入项目(L"葡萄 (Grape)", 105);

	// 2. 状态提示标签
	{
		标签::参数 tcs{ 235, 20, 255, 45 };
		tcs.标题 = L"总数: 5 | 现行选中: 无";
		提示标签.创建(tcs, this);
	}

	// 3. 操作按钮
	{
		按钮::参数 bcs{ 235, 75, 120, 32 };
		bcs.标题 = L"添加项目";
		添加按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 365, 75, 120, 32 };
		bcs.标题 = L"删除选中";
		删除按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 235, 115, 120, 32 };
		bcs.标题 = L"清空项目";
		清空按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 365, 115, 120, 32 };
		bcs.标题 = L"多选: 关";
		多选切换按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 235, 155, 120, 32 };
		bcs.标题 = L"自动排序: 关";
		排序切换按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 365, 155, 120, 32 };
		bcs.标题 = L"主题: 浅色";
		颜色切换按钮.创建(bcs, this);
	}
	{
		按钮::参数 bcs{ 235, 195, 250, 32 };
		bcs.标题 = L"读取所有被选中项";
		取选中列表按钮.创建(bcs, this);
	}

	窗口::完毕(模态);
}