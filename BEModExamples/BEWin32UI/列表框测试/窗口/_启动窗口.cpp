#include <BEMod.h>

struct __启动窗口 : 窗口
{
	void 事件_创建完毕()
	{
		_更新状态提示();
	}

	void 事件_尺寸被改变()
	{
	}

	void _更新状态提示()
	{
		int count = 列表框1.取项目数();
		int cur = 列表框1._取现行选中项();
		if (cur >= 0) {
			StrW text = 列表框1.取项目文本(cur);
			int val = 列表框1.取项目数值(cur);
			提示标签.标题_(L"总数: " + 到文本<W>(count) + L" | 现行选中: " + 到文本<W>(cur) + L"\n文本: " + text + L" (数值: " + 到文本<W>(val) + L")");
		} else {
			提示标签.标题_(L"总数: " + 到文本<W>(count) + L" | 现行选中: 无");
		}
	}

	void _列表框1_列表项被选择()
	{
		_更新状态提示();
	}

	void _列表框1_双击选择()
	{
		int cur = 列表框1._取现行选中项();
		if (cur >= 0) {
			StrW text = 列表框1.取项目文本(cur);
			int val = 列表框1.取项目数值(cur);
			信息框(L"双击了第 " + 到文本<W>(cur) + L" 项: " + text + L" (数值: " + 到文本<W>(val) + L")");
		}
	}

	void _添加按钮_被单击()
	{
		static int counter = 1;
		StrW txt = L"列表项目 " + 到文本<W>(counter);
		int val = counter * 100;
		列表框1.加入项目(txt, val);
		counter++;
		_更新状态提示();
	}

	void _删除按钮_被单击()
	{
		int cur = 列表框1._取现行选中项();
		if (cur >= 0) {
			列表框1.删除项目(cur);
			_更新状态提示();
		} else {
			信息框("请先选择要删除的项目");
		}
	}

	void _清空按钮_被单击()
	{
		列表框1.清空();
		_更新状态提示();
	}

	void _多选切换按钮_被单击()
	{
		bool 新状态 = !列表框1.允许选择多项;
		列表框1.允许选择多项_(新状态);
		多选切换按钮.标题_(新状态 ? L"多选: 开" : L"多选: 关");
		_更新状态提示();
	}

	void _排序切换按钮_被单击()
	{
		bool 新状态 = !列表框1.自动排序;
		列表框1.自动排序_(新状态);
		排序切换按钮.标题_(新状态 ? L"自动排序: 开" : L"自动排序: 关");
		_更新状态提示();
	}

	void _颜色切换按钮_被单击()
	{
		static bool isDark = false;
		isDark = !isDark;
		if (isDark) {
			列表框1.背景颜色_(RGB(35, 39, 46));
			列表框1.文本颜色_(RGB(97, 214, 214));
			颜色切换按钮.标题_(L"主题: 深色");
		} else {
			列表框1.背景颜色_(颜色::白色);
			列表框1.文本颜色_(颜色::黑色);
			颜色切换按钮.标题_(L"主题: 浅色");
		}
	}

	void _取选中列表按钮_被单击()
	{
		Arraybe<int> items;
		列表框1.取被选中项(items);
		if (items.count == 0) {
			信息框("当前没有任何选中的项目");
		} else {
			StrW res = L"共选中 " + 到文本<W>(items.count) + L" 项:\n";
			for (int i = 0; i < items.count; i++) {
				res = res + L"[" + 到文本<W>(items[i]) + L"] " + 列表框1.取项目文本(items[i]) + L"\n";
			}
			信息框(res);
		}
	}

#pragma region 组件成员
	struct _列表框1 : 列表框 {
		void 事件_列表项被选择() { _启动窗口._列表框1_列表项被选择(); }
		void 事件_双击选择() { _启动窗口._列表框1_双击选择(); }
	} 列表框1;

	标签 提示标签;

	struct _添加按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._添加按钮_被单击(); }
	} 添加按钮;

	struct _删除按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._删除按钮_被单击(); }
	} 删除按钮;

	struct _清空按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._清空按钮_被单击(); }
	} 清空按钮;

	struct _多选切换按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._多选切换按钮_被单击(); }
	} 多选切换按钮;

	struct _排序切换按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._排序切换按钮_被单击(); }
	} 排序切换按钮;

	struct _颜色切换按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._颜色切换按钮_被单击(); }
	} 颜色切换按钮;

	struct _取选中列表按钮 : 按钮 {
		void 事件_被单击() { _启动窗口._取选中列表按钮_被单击(); }
	} 取选中列表按钮;
#pragma endregion

	void 载入(窗口* 父窗 = 0, bool 模态 = 0);
	void 完毕(bool 模态 = 0);
} _启动窗口;