#include "../_启动窗口.h"

void __启动窗口::载入(窗口* 父窗, bool 模态)
{
	if (窗口句柄)return;

	窗口::参数 cs{ 0, 0, 380+5, 250+12 };
	//提供原生能力的支持！注意只有改为可拉伸的边框后才能进行拉伸
	cs.最大化按钮 = true; //提供双击标题栏自动最大化
	cs.最小化按钮 = true; //提供任务栏可进行最小化
	cs.边框 = 窗口边框::普通可调边框; //如改成它窗口边框::普通固定边框则不能拉伸
	窗口::创建(cs);
	
	this->完毕(模态);
}

void __启动窗口::完毕(bool 模态)
{
	SciterUI::参数 cs;
	cs.文件_html = "index.html";
	st.创建(cs, this);
	窗口::完毕(模态);
}
