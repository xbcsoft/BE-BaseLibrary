#include "stdafx.h"

事件信号自动 g_生产事件(true);   // 初始允许生产
事件信号自动 g_消费事件(false);  // 初始不允许消费

void 生产线程()
{
	for (int i = 0; i < 10; i++)
	{
		g_生产事件.等待();

		printf("生产线程：生产数据 %d\n", i);

		g_消费事件.置事件();
	}
}

void 消费线程()
{
	for (int i = 0; i < 10; i++)
	{
		g_消费事件.等待();

		printf("消费线程：消费数据 %d\n", i);

		g_生产事件.置事件();
	}
}

void main()
{
	线程 t1([]() { 生产线程(); });
	线程 t2([]() { 消费线程(); });

	t1.等待();
	t2.等待();

	printf("线程同步完成！\n");
}
